#!/usr/bin/env node
// Builds the Archistry website into ./_site (GitHub Pages or any static host).
//
//   node scripts/build.mjs --skill <path to the archistry skill repo>
//   node scripts/build.mjs --skill ../.claude/skills/archistry --serve        # preview at http://127.0.0.1:4173/
//   node scripts/build.mjs --skill skill --serve 8080
//
// The website lives in its own repository, so installing the skill never downloads it.
// The diagrams it shows are NOT copied into this repo: the build reads them from the skill repo
// (examples/, docs/previews/, docs/brand/, docs/how-it-works.*, .github/cover.png, scripts/lib/types.mjs).
// --skill defaults to $ARCHISTRY_SKILL, then ./skill (a checkout), then ../.claude/skills/archistry.
// No dependencies. Needs Node 18+.
import fs from 'node:fs';
import path from 'node:path';
import http from 'node:http';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(here, '_site');
const arg = (name) => { const i = process.argv.indexOf(name); return i > -1 ? process.argv[i + 1] : undefined; };

const candidates = [arg('--skill'), process.env.ARCHISTRY_SKILL, path.join(here, 'skill'), path.join(here, '..', '.claude', 'skills', 'archistry')].filter(Boolean);
const skill = candidates.map((p) => path.resolve(p)).find((p) => fs.existsSync(path.join(p, 'scripts', 'lib', 'types.mjs')));
if (!skill) {
  console.error('Cannot find the Archistry skill repo. Pass --skill <path> (a clone of https://github.com/abhishakec/archistry).');
  process.exit(1);
}
const { TYPES, STAGES, ASKS } = await import(pathToFileURL(path.join(skill, 'scripts', 'lib', 'types.mjs')).href);

const copyDir = (from, to, filter = () => true) => {
  if (!fs.existsSync(from)) return 0;
  let n = 0;
  fs.mkdirSync(to, { recursive: true });
  for (const e of fs.readdirSync(from, { withFileTypes: true })) {
    const a = path.join(from, e.name), b = path.join(to, e.name);
    if (e.isDirectory()) n += copyDir(a, b, filter);
    else if (filter(e.name)) { fs.copyFileSync(a, b); n++; }
  }
  return n;
};
const pngSize = (file) => { const b = fs.readFileSync(file); return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) }; };

// 1. the page itself
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
let files = 0;
for (const f of ['index.html', 'changelog.html', '404.html', 'CNAME']) { fs.copyFileSync(path.join(here, f), path.join(out, f)); files++; }
files += copyDir(path.join(here, 'assets'), path.join(out, 'assets'));
// the changelog reads the skill's GitHub releases, baked in here and refreshed live in the browser
await import('node:child_process').then(({ execFileSync }) => execFileSync(process.execPath, [path.join(here, 'scripts', 'fetch-releases.mjs'), path.join(out, 'releases.json')], { stdio: 'inherit' })); files++;
files += copyDir(path.join(here, 'img'), path.join(out, 'img'));

// 2. what it shows, read from the skill repo
files += copyDir(path.join(skill, 'examples'), path.join(out, 'examples'), (n) => /\.(html|drawio|json)$/.test(n));
files += copyDir(path.join(skill, 'docs', 'previews'), path.join(out, 'previews'), (n) => n.endsWith('.png'));
files += copyDir(path.join(skill, 'docs', 'brand'), path.join(out, 'brand'), (n) => /\.(svg|woff)$/.test(n));
for (const f of ['how-it-works.html', 'how-it-works.png', 'how-it-works.drawio', 'how-it-works.json']) {
  const a = path.join(skill, 'docs', f);
  if (fs.existsSync(a)) { fs.copyFileSync(a, path.join(out, f)); files++; }
}
fs.copyFileSync(path.join(skill, '.github', 'cover.png'), path.join(out, 'cover.png')); files++;

// 3. data.js: every type, their asks and picture sizes (a classic script, so the page also opens from file://)
const list = (Array.isArray(TYPES) ? TYPES : Object.values(TYPES)).map((t) => {
  const png = path.join(skill, 'docs', 'previews', t.name + '.png');
  const size = fs.existsSync(png) ? pngSize(png) : { w: 1600, h: 900 };
  return { name: t.name, stage: t.stage, engine: t.engine, question: t.answers, ask: ASKS[t.name] || '', aliases: t.aliases || [], w: size.w, h: size.h };
});
const engines = new Set(list.map((t) => t.engine)).size;
fs.writeFileSync(path.join(out, 'data.js'), `/* generated by scripts/build.mjs from the skill repo, do not edit */\nwindow.ARCHISTRY = ${JSON.stringify({ stages: STAGES, types: list, engines })};\n`);
fs.writeFileSync(path.join(out, '.nojekyll'), '');
files += 2;

const bytes = (function size(d) { return fs.readdirSync(d, { withFileTypes: true }).reduce((s, e) => s + (e.isDirectory() ? size(path.join(d, e.name)) : fs.statSync(path.join(d, e.name)).size), 0); })(out);
console.log(`built _site/  ·  ${files} files  ·  ${(bytes / 1048576).toFixed(1)} MB  ·  ${list.length} types, ${engines} engines  ·  from ${path.relative(here, skill) || '.'}`);

// 4. optional preview server
const si = process.argv.indexOf('--serve');
if (si > -1) {
  const port = Number(process.argv[si + 1]) || 4173;
  const mime = { '.html': 'text/html; charset=utf-8', '.css': 'text/css', '.js': 'text/javascript', '.json': 'application/json', '.png': 'image/png', '.svg': 'image/svg+xml', '.woff': 'font/woff', '.drawio': 'application/xml' };
  http.createServer((req, res) => {
    let p = decodeURIComponent(new URL(req.url, 'http://x').pathname);
    if (p.endsWith('/')) p += 'index.html';
    const file = path.join(out, p);
    if (!file.startsWith(out) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) {
      res.writeHead(404, { 'content-type': 'text/html; charset=utf-8' });
      return res.end(fs.readFileSync(path.join(out, '404.html')));
    }
    res.writeHead(200, { 'content-type': mime[path.extname(file)] || 'application/octet-stream' });
    fs.createReadStream(file).pipe(res);
  }).listen(port, '127.0.0.1', () => console.log(`preview: http://127.0.0.1:${port}/  (Ctrl+C to stop)`));
}
